import json
import logging
import os
import re
from typing import Any, Dict, List, Optional
from dotenv import load_dotenv

load_dotenv()

logger = logging.getLogger("edugenie.gemini")

DEFAULT_GEMINI_MODEL = os.getenv("GEMINI_MODEL", "gemini-2.5-flash")


class GeminiService:
    def __init__(self):
        self.api_key = os.getenv("GEMINI_API_KEY", "").strip()
        self.client = None
        self._init_client()

    def _init_client(self):
        """Initializes the google.genai Client if the API key is present."""
        self.api_key = os.getenv("GEMINI_API_KEY", "").strip()
        if self.api_key and self.api_key != "your_api_key_here":
            try:
                from google import genai
                self.client = genai.Client(api_key=self.api_key)
                logger.info("Google GenAI client initialized successfully.")
            except Exception as e:
                logger.error(f"Failed to initialize Google GenAI client: {e}")
                self.client = None
        else:
            self.client = None

    def is_available(self) -> bool:
        """Returns True if Gemini is configured with a valid-looking key."""
        if not self.client:
            self._init_client()
        return self.client is not None

    def generate_text(self, prompt: str, model_name: Optional[str] = None) -> str:
        """Generates text from Gemini using the configured prompt."""
        if not self.is_available():
            raise RuntimeError(
                "Gemini API key is not configured or invalid. "
                "Please set a valid GEMINI_API_KEY in your .env file."
            )

        model = model_name or os.getenv("GEMINI_MODEL", DEFAULT_GEMINI_MODEL)

        try:
            response = self.client.models.generate_content(
                model=model,
                contents=prompt,
            )
            if response and response.text:
                return response.text.strip()
            return "No response was generated by the model."
        except Exception as e:
            err_msg = str(e)
            logger.error(f"Gemini API error: {err_msg}")
            # If 2.5-flash is not found or quota exceeded, try fallback model
            if "not found" in err_msg.lower() or "404" in err_msg:
                try:
                    logger.info("Attempting fallback to gemini-1.5-flash...")
                    fallback_response = self.client.models.generate_content(
                        model="gemini-1.5-flash",
                        contents=prompt,
                    )
                    if fallback_response and fallback_response.text:
                        return fallback_response.text.strip()
                except Exception as fb_err:
                    logger.error(f"Fallback model error: {fb_err}")
            raise RuntimeError(f"Error communicating with Google Gemini: {err_msg}")

    def generate_quiz_json(self, prompt: str, num_questions: int = 5) -> List[Dict[str, Any]]:
        """Generates and safely parses structured multiple-choice quiz questions."""
        raw_text = self.generate_text(prompt)

        # Attempt to clean markdown backticks if returned
        cleaned = raw_text.strip()
        if "```" in cleaned:
            # Extract content inside ```json ... ``` or ``` ... ```
            match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", cleaned, re.IGNORECASE)
            if match:
                cleaned = match.group(1).strip()

        # Parse JSON
        try:
            data = json.loads(cleaned)
        except json.JSONDecodeError:
            # Fallback regex search for json array [...]
            array_match = re.search(r"\[\s*\{.*\}\s*\]", cleaned, re.DOTALL)
            if array_match:
                try:
                    data = json.loads(array_match.group(0))
                except Exception as ex:
                    logger.error(f"Failed regex array parse: {ex}")
                    raise RuntimeError("Received malformed quiz data from AI. Please try again.")
            else:
                raise RuntimeError("Failed to parse structured quiz data from AI. Please try again.")

        if not isinstance(data, list):
            raise RuntimeError("Quiz output did not return a valid list of questions.")

        # Validate each item
        validated_items = []
        for i, item in enumerate(data[:num_questions]):
            question = item.get("question") or f"Question {i+1}"
            opt_a = item.get("option_a") or item.get("A") or "Option A"
            opt_b = item.get("option_b") or item.get("B") or "Option B"
            opt_c = item.get("option_c") or item.get("C") or "Option C"
            opt_d = item.get("option_d") or item.get("D") or "Option D"
            correct = str(item.get("correct_option") or item.get("correctAnswer") or "A").strip().upper()
            if correct not in ["A", "B", "C", "D"]:
                # Normalise if full option or index given
                if "1" in correct:
                    correct = "A"
                elif "2" in correct:
                    correct = "B"
                elif "3" in correct:
                    correct = "C"
                elif "4" in correct:
                    correct = "D"
                else:
                    correct = "A"

            validated_items.append({
                "question": str(question).strip(),
                "option_a": str(opt_a).strip(),
                "option_b": str(opt_b).strip(),
                "option_c": str(opt_c).strip(),
                "option_d": str(opt_d).strip(),
                "correct_option": correct,
                "explanation": str(item.get("explanation", "")).strip()
            })

        return validated_items


# Global singleton instance
gemini_service = GeminiService()
